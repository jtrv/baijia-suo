// ---- Green-rust palette ----------------------------------------------------
//
// Jakob Westhoff's `green_rust` paints each falling stream as:
//   head           -> pure white
//   1 below head   -> bright pure green
//   middle of tail -> medium green
//   last cell      -> dim/dark green
// then nothing (background black).
//
// We use a five-stop ramp interpolated across the trail so the fade reads
// smoothly on a high-res framebuffer (the original is at terminal-cell
// resolution, but we have many more pixels per glyph). Index 0 is the head.

const HEAD_COLOR: Color = Color { a: 255, r: 255, g: 255, b: 255 };
const BG: Color = Color { a: 255, r: 0,   g: 0,   b: 0   };

// Five reference points for the green ramp behind the head.
// rgb values picked to match terminal palettes: bright green, mid green,
// darker green, dim green, very dim green.
const TRAIL_RAMP: &[Color] = &[
    Color { a: 255, r: 170, g: 255, b: 170 }, // just below head: pale green
    Color { a: 255, r:   0, g: 255, b:   0 }, // bright green
    Color { a: 255, r:   0, g: 200, b:   0 }, // medium-bright
    Color { a: 255, r:   0, g: 140, b:   0 }, // medium
    Color { a: 255, r:   0, g:  80, b:   0 }, // dim
    Color { a: 255, r:   0, g:  40, b:   0 }, // very dim / tail end
];

/// Per-cell glyph index for a column. A value of -1 means "no glyph drawn".
const EMPTY_GLYPH: i32 = -1;

/// One falling stream. Each "row" in `glyphs` represents one glyph-row of
/// the screen for this column.
#[derive(Clone)]
struct Column {
    /// Glyph index for each row (length == rows). EMPTY_GLYPH means blank.
    glyphs: Vec<i32>,
    /// Row index of the bright head. Streams run from 0 (top) downward.
    /// When negative, the stream hasn't yet entered the screen.
    head: i32,
    /// Length of the visible trail (head + this many cells of green fade).
    trail_len: i32,
    /// Frames between advancing this column by one row (column "speed").
    /// Smaller = faster.
    step_frames: u32,
    /// Frame counter modulo step_frames.
    step_counter: u32,
}

pub struct Matrix {
    columns: RefCell<Vec<Column>>,
    /// Pixel width allocated per column (>= KATAKANA_CELL_WIDTH).
    col_pitch_px: i32,
    /// Rows of glyphs that fit on the screen.
    rows: i32,
    /// Horizontal pixel offset for the very first column (centres the grid).
    x_origin: i32,
    width: u32,
    height: u32,
    delay_us: u64,
}

impl Matrix {
    /// Return true if the bit for atlas pixel (sx, sy) is set.
    fn atlas_bit(sx: i32, sy: i32) -> bool {
        if sx < 0 || !(0..KATAKANA_CELL_HEIGHT).contains(&sy) {
            return false;
        }
        let byte_idx = (sy * KATAKANA_ATLAS_STRIDE_BYTES + sx / 8) as usize;
        if byte_idx >= KATAKANA_BITS.len() {
            return false;
        }
        let bit_idx = (sx % 8) as u32;
        // Per existing matrix.rs convention: a set bit (1) marks a foreground
        // pixel. (xlockmore data convention.)
        ((KATAKANA_BITS[byte_idx] >> bit_idx) & 1) != 0
    }

    /// Draw a single glyph at the given (dst_x, dst_y) pixel position.
    fn draw_glyph(
        buffer: &mut [u8],
        width: u32,
        height: u32,
        dst_x: i32,
        dst_y: i32,
        glyph_idx: i32,
        color: Color,
    ) {
        if glyph_idx < 0 {
            return;
        }
        let src_x_base = glyph_idx * KATAKANA_CELL_WIDTH;
        for cy in 0..KATAKANA_CELL_HEIGHT {
            for cx in 0..KATAKANA_CELL_WIDTH {
                if Self::atlas_bit(src_x_base + cx, cy) {
                    put_pixel(buffer, width, height, dst_x + cx, dst_y + cy, color);
                }
            }
        }
    }

    /// Sample the trail color for the n-th cell behind the head, given a
    /// total trail length. n == 0 is the cell directly behind the head; the
    /// final cell maps to the dimmest entry of TRAIL_RAMP.
    fn trail_color(n: i32, trail_len: i32) -> Color {
        if trail_len <= 1 {
            return TRAIL_RAMP[TRAIL_RAMP.len() - 1];
        }
        // Map [0 .. trail_len-1] -> ramp index [0 .. ramp_max].
        let ramp_max = (TRAIL_RAMP.len() - 1) as f32;
        let t = (n as f32 / (trail_len - 1) as f32).clamp(0.0, 1.0);
        let pos = t * ramp_max;
        let i0 = pos.floor() as usize;
        let i1 = (i0 + 1).min(TRAIL_RAMP.len() - 1);
        let f = pos - i0 as f32;
        let a = TRAIL_RAMP[i0];
        let b = TRAIL_RAMP[i1];
        Color::new(
            255,
            ((a.r as f32) * (1.0 - f) + (b.r as f32) * f) as u8,
            ((a.g as f32) * (1.0 - f) + (b.g as f32) * f) as u8,
            ((a.b as f32) * (1.0 - f) + (b.b as f32) * f) as u8,
        )
    }

    /// Reinitialise a column to start a fresh fall from above the top of
    /// the screen with a random offset, speed, and trail length.
    fn respawn(&self, c: &mut Column) {
        let mut rng = rand::rng();

        for slot in c.glyphs.iter_mut() {
            *slot = EMPTY_GLYPH;
        }

        // Random start offset above the top so streams don't all reappear
        // at the same y when the screen first comes up or when one finishes.
        let lead = rng.random_range(2..=(self.rows.max(4)));
        c.head = -lead;

        // Trail length in cells: pick something proportional to screen
        // height but with plenty of variety. green_rust uses
        // (rand 8..rows) by default; do the same with a sensible floor.
        let min_trail = 6;
        let max_trail = (self.rows / 2).max(min_trail + 2);
        c.trail_len = rng.random_range(min_trail..=max_trail);

        // Per-column fall speed: number of frames per row advance.
        // Smaller value => faster column. We aim for ~50-80 ms per row at
        // delay_us = 20_000 (50 fps); that's 3-4 frames/row. Add jitter.
        // Range 2..=6 keeps the spread satisfying without being chaotic.
        c.step_frames = rng.random_range(2..=6);
        c.step_counter = 0;
    }
}

impl Animation for Matrix {
    fn new(config: &AnimConfig) -> Self {
        let mut m = Matrix {
            columns: RefCell::new(Vec::new()),
            col_pitch_px: KATAKANA_CELL_WIDTH,
            rows: 0,
            x_origin: 0,
            width: config.width,
            height: config.height,
            delay_us: config.delay_us,
        };
        m.reset(config);
        m
    }

    fn tick(&mut self) {
        let mut rng = rand::rng();
        let mut columns = self.columns.borrow_mut();

        for c in columns.iter_mut() {
            c.step_counter += 1;
            let mut advanced = false;
            if c.step_counter >= c.step_frames {
                c.step_counter = 0;
                c.head += 1;
                advanced = true;

                // When the *tail end* has fallen off the bottom of the
                // screen, respawn the stream from above the top with a
                // fresh random configuration.
                let tail_row = c.head - c.trail_len;
                if tail_row >= self.rows {
                    self.respawn(c);
                }
            }

            // When we advance, the new head cell picks a fresh glyph.
            // Otherwise, occasionally mutate a random visible glyph in the
            // trail (subtle flicker, ala green_rust).
            if advanced {
                if c.head >= 0 && (c.head as usize) < c.glyphs.len() {
                    c.glyphs[c.head as usize] =
                        rng.random_range(0..KATAKANA_NUM_CELLS);
                }
            } else {
                // ~5% chance per frame per column to mutate one trail cell.
                if rng.random_range(0..100) < 5 {
                    let tail_row = (c.head - c.trail_len + 1).max(0);
                    let head_row = c.head.min(self.rows - 1);
                    if head_row >= tail_row {
                        let row = rng.random_range(tail_row..=head_row) as usize;
                        if row < c.glyphs.len() {
                            c.glyphs[row] =
                                rng.random_range(0..KATAKANA_NUM_CELLS);
                        }
                    }
                }
            }
        }
    }

    fn render(&self, buffer: &mut [u8], width: u32, height: u32) {
        // We clear each frame, so just paint visible cells from per-column state.
        let columns = self.columns.borrow();
        for (i, c) in columns.iter().enumerate() {
            let x = self.x_origin + (i as i32) * self.col_pitch_px;

            // The cell at row == c.head is the bright white head.
            // Cells at row == c.head - 1, c.head - 2, ... c.head - (trail_len - 1)
            // form the green-fading trail.
            for n in 0..c.trail_len {
                let row = c.head - n;
                if row < 0 || row >= self.rows {
                    continue;
                }
                let row_usize = row as usize;
                if row_usize >= c.glyphs.len() {
                    continue;
                }
                let glyph = c.glyphs[row_usize];
                if glyph == EMPTY_GLYPH {
                    continue;
                }

                let y = row * KATAKANA_CELL_HEIGHT;
                let color = if n == 0 {
                    HEAD_COLOR
                } else {
                    // n=1 is the cell just behind the head; map to ramp idx 0.
                    Self::trail_color(n - 1, c.trail_len - 1)
                };
                Self::draw_glyph(buffer, width, height, x, y, glyph, color);
            }
        }
        // Suppress unused warning if BG ever becomes unreferenced.
        let _ = BG;
    }

    fn reset(&mut self, config: &AnimConfig) {
        self.width = config.width;
        self.height = config.height;
        self.delay_us = config.delay_us;

        // Pack columns as tightly as the glyphs allow; this matches
        // green_rust where each terminal column carries one stream.
        self.col_pitch_px = KATAKANA_CELL_WIDTH;
        let num_cols = (self.width as i32 / self.col_pitch_px).max(1);
        // Centre the grid horizontally so leftover pixels split evenly.
        let used_width = num_cols * self.col_pitch_px;
        self.x_origin = ((self.width as i32) - used_width) / 2;

        self.rows = (self.height as i32 / KATAKANA_CELL_HEIGHT).max(1);

        let mut cols = Vec::with_capacity(num_cols as usize);
        for _ in 0..num_cols {
            let mut c = Column {
                glyphs: vec![EMPTY_GLYPH; self.rows as usize],
                head: 0,
                trail_len: 0,
                step_frames: 1,
                step_counter: 0,
            };
            self.respawn(&mut c);

            // Stagger the initial head positions so the screen doesn't
            // start with every stream in lock-step above the top edge.
            let mut rng = rand::rng();
            c.head = rng.random_range(-(self.rows)..self.rows);
            // Pre-fill any rows already on-screen with random glyphs so
            // streams that start mid-screen look natural.
            let tail_row = c.head - c.trail_len + 1;
            let first = tail_row.max(0) as usize;
            let last = c.head.clamp(0, self.rows - 1) as usize;
            for row in first..=last {
                if row < c.glyphs.len() {
                    c.glyphs[row] = rng.random_range(0..KATAKANA_NUM_CELLS);
                }
            }

            cols.push(c);
        }
        self.columns = RefCell::new(cols);
    }

    fn render_policy(&self) -> RenderPolicy {
        RenderPolicy::ClearThenRender
    }

    fn frame_delay_us(&self) -> u64 {
        self.delay_us
    }
}
